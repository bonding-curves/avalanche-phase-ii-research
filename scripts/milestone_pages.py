def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def flat_check(check: dict[str, Any] | None) -> dict[str, Any] | None:
    """One shape for both check receipts: the dataset check, and the command result that nests it under ``validation``."""
    if check is None or "validation" not in check:
        return check
    inner = check["validation"]
    return {**inner, "status": inner.get("status", check.get("status")), "findings": inner.get("findings", check.get("findings", []))}


def utc_instant(text: str) -> datetime:
    """A timestamp must identify an instant, including its UTC offset."""
    value = datetime.fromisoformat(text.replace("Z", "+00:00"))
    if value.tzinfo is None:
        raise ValueError("timestamp must include Z or a UTC offset")
    return value.astimezone(UTC)


def as_of_value(text: str) -> str:
    """Validate a legacy whole-day cutoff or normalize an exact instant to UTC."""
    if re.fullmatch(r"\d{4}-\d{2}-\d{2}", text):
        return date.fromisoformat(text).isoformat()
    return utc_instant(text).isoformat().replace("+00:00", "Z")


def cutoff_instant(text: str) -> datetime:
    value = as_of_value(text)
    return datetime.combine(date.fromisoformat(value), time.max, UTC) if len(value) == 10 else utc_instant(value)


def latest_runs(runs_root: Path, as_of: str | None = None) -> dict[str, dict[str, Any]]:
    """Newest built run per dataset, completed on or before ``as_of`` when given, with its capture, build, and check receipts."""
    cutoff = cutoff_instant(as_of) if as_of else None
    latest: dict[str, dict[str, Any]] = {}
    if not runs_root.is_dir():
        return latest
    for directory in sorted(runs_root.iterdir()):
        build_path, capture_path = directory / "dataset" / "build.json", directory / "capture" / "capture.json"
        if not build_path.is_file() or not capture_path.is_file():
            continue
        build, capture = load_json(build_path), load_json(capture_path)
        if build.get("source_capture_id") != capture.get("capture_id"):
            continue
        completed = build.get("completed_at") or ""
        if cutoff is not None and utc_instant(completed) > cutoff:
            continue
        check_path = directory / "dataset" / "check.json"
        record = {"run": directory.name, "build": build, "capture": capture,
                  "check": flat_check(load_json(check_path)) if check_path.is_file() else None}
        current = latest.get(build["dataset_id"])
        if current is None or utc_instant(completed) > utc_instant(current["build"].get("completed_at") or ""):
            latest[build["dataset_id"]] = record
    return latest


def load_pins(pins_root: Path, as_of: str | None = None) -> dict[str, list[tuple[str, str]]]:
    """For each dataset, the (pin, run) pairs that freeze one of its runs."""
    cutoff = cutoff_instant(as_of) if as_of else None
    pinned: dict[str, list[tuple[str, str]]] = {}
    if not pins_root.is_dir():
        return pinned
    for path in sorted(pins_root.glob("*.json")):
        pin = load_json(path)
        if cutoff is not None and utc_instant(pin.get("pinned_at") or "") > cutoff:
            continue
        for item in pin.get("runs", []):
            pinned.setdefault(item["dataset_id"], []).append((pin["name"], item["run"]))
    return pinned


def raw_hash(capture: dict[str, Any]) -> str:
    items = capture.get("responses") or capture.get("queries") or capture.get("inputs") or capture.get("files") or []
    return ", ".join(item["sha256"][:12] for item in items[:2]) + (" ..." if len(items) > 2 else "")


def hash_cell(capture: dict[str, Any]) -> str:
    """The raw data hash as code, or "none recorded" when the capture lists no responses, queries, inputs or files."""
    hashed = raw_hash(capture)
    return f"`{hashed}`" if hashed else "none recorded"


def request_text(source: dict[str, Any], definition: dict[str, Any], record: dict[str, Any] | None = None) -> str:
    """What a dataset is made from. A derived dataset names the inputs its run read, else the catalog's declared inputs."""
    if "inputs" in source:
        read = [item["dataset_id"] for item in (record or {}).get("capture", {}).get("inputs", []) if item.get("dataset_id")]
        wanted = list(dict.fromkeys(read)) or [item["dataset_id"] for item in source["inputs"] if item["id"] in definition["input_ids"]]
        return "derived from " + ", ".join(f"`{dataset_id}`" for dataset_id in wanted)
    if "queries" in source:
        return "SQL " + ", ".join(f"`{item['sql']}`" for item in source["queries"] if item["id"] in definition["query_ids"])
    count = len(definition["endpoint_ids"])
    first = next(item for item in source["endpoints"] if item["id"] == definition["endpoint_ids"][0])
    method = "POST" if "request_json" in first else "GET"
    url = first["url"].split("?")[0]
    return f"{method} `{url}`" if count == 1 else f"{count} {method} requests, the first to `{url}`"


def coverage(summary: dict[str, Any], capture: dict[str, Any] | None = None) -> str:
    """The dates a build covers, from its summary, else its capture window, else its snapshot time."""
    for start, end in DATE_KEYS:
        if summary.get(start) and summary.get(end):
            return f"{str(summary[start])[:10]} to {str(summary[end])[:10]}"
    window = (capture or {}).get("window") or {}
    if window.get("start") and window.get("end"):
        return f"{str(window['start'])[:10]} to {str(window['end'])[:10]}"
    observed = summary.get("observed_at") or summary.get("last_observation_at")
    return f"snapshot {str(observed)[:16].replace('T', ' ')}" if observed else "not dated"


def span(dataset_id: str, runs: dict[str, dict[str, Any]]) -> str:
    """Dates a dataset covers. A seamed table runs from the share's first row to the end of the walk's window."""
    record = runs.get(dataset_id)
    if record is None:
        return "no built run"
    text = coverage(record["build"].get("summary", {}), record["capture"])
    share = runs.get(dataset_id.replace("derived.seamed-", "snowflake.primary-")) if dataset_id.startswith("derived.seamed-") else None
    if share is None or " to " not in text:
        return text
    first = coverage(share["build"].get("summary", {})).split(" to ")[0]
    return f"{first} to {text.split(' to ')[1]}" if first[:1].isdigit() else text


def counted(value: Any) -> str:
    return f"{value:,}" if isinstance(value, int) and not isinstance(value, bool) else str(value)


def build_counts(record: dict[str, Any]) -> list[str]:
    """The build's counts worth review, in a reader's words."""
    summary = record["build"].get("summary", {})
    return [f"{GAP_PHRASES[key]}: {counted(summary[key])}" for key in GAP_PHRASES if summary.get(key) not in (0, None, {}, [], False)]


def checks(record: dict[str, Any] | None) -> str:
    if record is None or record["check"] is None:
        return "not checked"
    check = record["check"]
    run, found = len(check.get("checked", [])), len(check.get("findings", []))
    if check.get("status") == "pass" and not found:
        return f"all {run} passed" if run else "passed"
    return f"{found} finding{'s' if found != 1 else ''} from {run} checks"


def cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def rows_of(record: dict[str, Any] | None) -> str:
    rows = record["build"].get("summary", {}).get("rows") if record else None
    return counted(rows) if rows is not None else "not counted"


def long_date(text: str) -> str:
    day = date.fromisoformat(text[:10])
    return f"{day.day} {day:%B %Y}"


def as_of_label(text: str) -> str:
    """Readable cutoff without losing the instant needed for reproduction."""
    if len(text) == 10:
        return long_date(text)
    value = utc_instant(text)
    return f"{long_date(value.date().isoformat())} at {value:%H:%M:%S}" + (f".{value.microsecond:06d}" if value.microsecond else "") + " UTC"


def primary(quantity: str, runs: dict[str, dict[str, Any]]) -> str:
    candidates = PRIMARY[quantity][0]
    return next((dataset_id for dataset_id in candidates if dataset_id in runs), candidates[-1])


def as_of_date(runs: dict[str, dict[str, Any]], as_of: str | None) -> str:
    newest = max((record["build"]["completed_at"] for record in runs.values()), key=utc_instant) if runs else ""
    return as_of_value(as_of or newest) if as_of or newest else ""


