def chart_caption(number: int) -> str:
    """The coverage chart's caption, with its ranges read from the chart's own data file."""
    rows = chart_rows()
    month = lambda text: date.fromisoformat(text[:7] + "-01").strftime("%B %Y")
    ranges = ""
    if rows:
        first, last = rows[0], rows[-1]
        peak = max(rows, key=lambda r: int(r["Delegations"]))
        low = min(rows, key=lambda r: int(r["Validator staking periods"]))
        high = max(rows, key=lambda r: int(r["Validator staking periods"]))
        ranges = (f"Delegations rise from {int(first['Delegations']):,} in {month(first['Month accepted'])} to a peak of "
                  f"{int(peak['Delegations']):,} in {month(peak['Month accepted'])}. Validator staking periods range from "
                  f"{int(low['Validator staking periods']):,} in {month(low['Month accepted'])} to "
                  f"{int(high['Validator staking periods']):,} in {month(high['Month accepted'])}. The last month drawn is "
                  f"{month(last['Month accepted'])}, the last complete month of the run. ")
    run = chart_run()
    source = f"Source: run `{run}` of `derived.staking-periods`." if run else "Source: `derived.staking-periods`."
    return (f"*Figure {number}. Staking periods accepted per month, by the month the stake was accepted, on a logarithmic scale. "
            + ranges + "Dotted lines mark network upgrades. The green line marks the seam on the day Helicon activated. "
            f"The [interactive chart]({ROUTE}/{CHART}.html) gives each month's counts, and its [data]({ROUTE}/{CHART}.csv) holds exactly "
            f"the values drawn. {source}*")


def continuity() -> str:
    """A sentence on whether the chart's months run without a break, read from the chart's data file."""
    rows = chart_rows()
    if not rows:
        return ""
    months = [date.fromisoformat(row["Month accepted"] + "-01") for row in rows]
    steps = all((b.year - a.year) * 12 + b.month - a.month == 1 for a, b in itertools.pairwise(months))
    filled = all(int(row["Delegations"]) > 0 and int(row["Validator staking periods"]) > 0 for row in rows)
    if steps and filled:
        return (f"Every month from {months[0]:%B %Y} to {months[-1]:%B %Y} holds both validator staking periods and "
                "delegations, so the record has no empty month. ")
    return "Some months hold no staking periods of one kind. "


def seam_table(runs: dict[str, dict[str, Any]]) -> list[str]:
    lines = ["| Table | Rows compared before the seam | Rows that differ | Share rows missing from the walk | Rows from the share | Rows from the walk |",
             "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for dataset_id, label in SEAMED:
        record = runs.get(dataset_id)
        if record is None:
            continue
        summary = record["build"].get("summary", {})
        overlap, sources = summary.get("overlap", {}), summary.get("rows_by_source", {})
        differing = sum((overlap.get("differing_by_column") or {}).values())
        lines.append(f"| {label} (`{dataset_id}`) | {counted(overlap.get('rows_compared', 0))} | {counted(differing)} | "
                     f"{counted(overlap.get('share_rows_missing_in_backup', 0))} | {counted(sources.get('snowflake', 0))} | "
                     f"{counted(sources.get('backup', 0))} |")
    return lines if len(lines) > 2 else []


def seam_agreed(runs: dict[str, dict[str, Any]]) -> bool:
    overlaps = [runs[dataset_id]["build"].get("summary", {}).get("overlap", {}) for dataset_id, _ in SEAMED if dataset_id in runs]
    return bool(overlaps) and all(not sum((item.get("differing_by_column") or {}).values()) and not item.get("share_rows_missing_in_backup")
                                  for item in overlaps)


def attention(catalog: dict[str, Any], runs: dict[str, dict[str, Any]]) -> list[str]:
    return [d["id"] for d in catalog["datasets"] if d["id"] in runs and runs[d["id"]]["check"]
            and (runs[d["id"]]["check"].get("status") != "pass" or runs[d["id"]]["check"].get("findings"))]


def unchecked(catalog: dict[str, Any], runs: dict[str, dict[str, Any]]) -> list[str]:
    """Built datasets with no check result. They are neither passed nor flagged."""
    return [d["id"] for d in catalog["datasets"] if d["id"] in runs and runs[d["id"]]["check"] is None]


def missing_quantities(runs: dict[str, dict[str, Any]]) -> list[str]:
    """Quantities of the agreement with no built run of any dataset that answers them."""
    return [quantity for quantity, (ids, _) in PRIMARY.items() if not any(dataset_id in runs for dataset_id in ids)]


