#!/usr/bin/env python3
"""Generate the Milestone 1.1 and 1.2 evidence pages from the data catalog and the built run receipts.

Standard library only, so the site's Python tests can run it without the research environment. The pages are
generated output: edit the catalog, rebuild a dataset, or rerun a check, then run ``build`` again.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "data" / "data-catalog.json"
RUNS = ROOT / "data" / "runs"
PAGES = {
    "ingestion": ROOT / "content" / "Phase II" / "Milestones" / "Milestone 1" / "1-1 Data Ingestion" / "index.md",
    "manifest": ROOT / "content" / "Phase II" / "Milestones" / "Milestone 1" / "1-2 Data Manifest" / "index.md",
}
MARKER = "<!-- generated by scripts/milestone_pages.py; edit the data catalog or rebuild a dataset, then run: python scripts/milestone_pages.py build -->"
QUANTITIES = ("validator flows", "delegator flows", "rewards", "durations", "context")
GAP_KEYS = ("rows_without_", "rows_rewarded_without_", "skipped_dates", "dates_with_two_observations", "days_with_a_missing_series",
            "rows_in_blocks_where_", "rows_with_several_", "pools_flagged_outlier", "partial_day_rows", "genesis_rows")


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def latest_runs(runs_root: Path) -> dict[str, dict[str, Any]]:
    """Newest built run per dataset, with its capture, build, and check receipts."""
    latest: dict[str, dict[str, Any]] = {}
    if not runs_root.is_dir():
        return latest
    for directory in sorted(runs_root.iterdir()):
        build_path, capture_path = directory / "dataset" / "build.json", directory / "capture" / "capture.json"
        if not build_path.is_file() or not capture_path.is_file():
            continue
        build, capture = load_json(build_path), load_json(capture_path)
        if build.get("source_capture_id") != capture.get("capture_id"):
            continue
        check_path = directory / "dataset" / "check.json"
        record = {"run": directory.name, "build": build, "capture": capture, "check": load_json(check_path) if check_path.is_file() else None}
        current = latest.get(build["dataset_id"])
        if current is None or (build.get("completed_at") or "") > (current["build"].get("completed_at") or ""):
            latest[build["dataset_id"]] = record
    return latest


def raw_hash(capture: dict[str, Any]) -> str:
    items = capture.get("responses") or capture.get("queries") or capture.get("inputs") or []
    return ", ".join(item["sha256"][:12] for item in items[:2]) + (" ..." if len(items) > 2 else "")


def request_text(source: dict[str, Any], definition: dict[str, Any]) -> str:
    if "inputs" in source:
        wanted = [item["dataset_id"] for item in source["inputs"] if item["id"] in definition["input_ids"]]
        return "derived from " + ", ".join(f"`{dataset_id}`" for dataset_id in wanted)
    if "queries" in source:
        return ", ".join(f"`{item['sql']}`" for item in source["queries"] if item["id"] in definition["query_ids"])
    count = len(definition["endpoint_ids"])
    first = next(item for item in source["endpoints"] if item["id"] == definition["endpoint_ids"][0])
    method = "POST " if "request_json" in first else ""
    return f"{method}{count} request{'s' if count > 1 else ''} to `{first['url'].split('?')[0]}`"


def coverage(summary: dict[str, Any]) -> str:
    starts = [value for key, value in summary.items() if key.endswith("_from") and value]
    ends = [value for key, value in summary.items() if key.endswith("_to") and value]
    if starts and ends:
        return f"{str(starts[0])[:10]} to {str(ends[0])[:10]}"
    observed = summary.get("observed_at") or summary.get("last_observation_at")
    return f"snapshot {str(observed)[:19]}" if observed else "n/a"


def gaps(record: dict[str, Any] | None) -> str:
    if record is None:
        return "no built run"
    items = []
    if record["check"]:
        items.extend(record["check"].get("findings", []))
    for key, value in record["build"].get("summary", {}).items():
        if any(key.startswith(prefix) or key == prefix for prefix in GAP_KEYS) and value not in (0, None, {}):
            items.append(f"{key.replace('_', ' ')}: {value}")
    return "; ".join(items) if items else "none recorded"


def checks(record: dict[str, Any] | None) -> str:
    if record is None or record["check"] is None:
        return "not checked"
    check = record["check"]
    return f"{check['status']}, {len(check.get('checked', []))} checks, {len(check.get('findings', []))} findings"


def cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(catalog: dict[str, Any], runs: dict[str, dict[str, Any]]) -> dict[str, str]:
    sources = {item["id"]: item for item in catalog["sources"]}
    datasets = catalog["datasets"]
    built = sum(1 for item in datasets if item["id"] in runs)

    ingestion = [
        "---", 'title: "1.1 Data Ingestion"', 'description: "Contract deliverable 1.1: Data Ingestion."',
        "status: delivered", "source: signed-grant-agreement", 'tags: ["staking-duration-and-liquidity", "issuance-and-rewards", "delegation-market"]', "---", "", MARKER, "",
        "## Contract requirement", "", "Ingest Avalanche-provided historical data (validator/delegator flows, rewards, durations)", "",
        "## Evidence status", "",
        f"{built} of {len(datasets)} declared datasets have a built run. Each resolves to a source contract in `data/data-catalog.json`, "
        "an immutable capture receipt, a typed Parquet build, and a persisted check result. Delivered for the Avalanche team's review. Not yet accepted.", "",
        "### Coverage by contract quantity", "",
        "| Quantity | Dataset | Coverage | Rows | Checks |", "| --- | --- | --- | ---: | --- |",
    ]
    for quantity in QUANTITIES:
        for definition in datasets:
            if quantity not in definition.get("contract_quantities", []):
                continue
            record = runs.get(definition["id"])
            summary = record["build"].get("summary", {}) if record else {}
            ingestion.append(f"| {quantity} | `{definition['id']}` | {cell(coverage(summary))} | {summary.get('rows', 'n/a')} | {cell(checks(record))} |")
    ingestion += ["", "### Known gaps", ""]
    for definition in datasets:
        text = gaps(runs.get(definition["id"]))
        if text not in ("none recorded",):
            ingestion.append(f"- `{definition['id']}`: {cell(text)}")
    ingestion += ["", "Captures are working data and are not committed; the `data/README.md` guide reproduces them.", "",
                  "[Signed Grant Agreement](/Phase-II/Milestones/Milestone-0/Signed-Grant-Agreement)", ""]

    manifest = [
        "---", 'title: "1.2 Data Manifest"', 'description: "Contract deliverable 1.2: Data Manifest."',
        "status: delivered", "source: signed-grant-agreement", 'tags: ["issuance-and-rewards", "staking-duration-and-liquidity", "fees-and-value-capture"]', "---", "", MARKER, "",
        "## Contract requirement", "", "Documentation of sources, transformations, quality metrics", "",
        "## Evidence status", "",
        "The manifest is machine-readable: `data/data-catalog.json` declares every source and dataset with fields, units, and derivations, "
        "`avalanche data manifest --json` renders it, and each built run carries capture, build, and check receipts. This page is generated from those records.", "",
        "### Sources", "", "| Source | Authority | Authentication |", "| --- | --- | --- |",
    ]
    for source in catalog["sources"]:
        manifest.append(f"| `{source['id']}` | {cell(source['authority'])} | {cell(source['authentication'])} |")
    manifest += ["", "### Datasets", "", "| Dataset | Source | Query or request | Fields | Used by |", "| --- | --- | --- | ---: | --- |"]
    for definition in datasets:
        manifest.append(f"| `{definition['id']}` | `{definition['source_id']}` | {cell(request_text(sources[definition['source_id']], definition))} | {len(definition['fields'])} | {cell('; '.join(definition.get('studies', [])))} |")
    manifest += ["", "### Latest runs", "", "| Dataset | Captured | Capture ID | Raw hash | Rows | Checks | Findings and gaps |", "| --- | --- | --- | --- | ---: | --- | --- |"]
    for definition in datasets:
        record = runs.get(definition["id"])
        if record is None:
            manifest.append(f"| `{definition['id']}` | no built run | | | | | |")
            continue
        capture, build = record["capture"], record["build"]
        manifest.append(
            f"| `{definition['id']}` | {capture.get('completed_at', '')} | `{capture.get('capture_id', '')}` | `{raw_hash(capture)}` | "
            f"{build.get('summary', {}).get('rows', 'n/a')} | {cell(checks(record))} | {cell(gaps(record))} |"
        )
    manifest += ["", "Units are preserved as served and converted once where the catalog says so. Delivered for the Avalanche team's review. Not yet accepted.", "",
                 "[Signed Grant Agreement](/Phase-II/Milestones/Milestone-0/Signed-Grant-Agreement)", ""]
    return {"ingestion": "\n".join(ingestion), "manifest": "\n".join(manifest)}


def validate(catalog: dict[str, Any], pages: dict[str, Path]) -> list[str]:
    """Structural check of the committed pages: generated marker and every dataset present."""
    problems = []
    for name, path in pages.items():
        if not path.is_file():
            problems.append(f"missing page: {path}")
            continue
        text = path.read_text(encoding="utf-8")
        if MARKER not in text:
            problems.append(f"{path.name} lacks the generated marker")
        for definition in catalog["datasets"]:
            if f"`{definition['id']}`" not in text:
                problems.append(f"{path.name} does not mention {definition['id']}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("build", "check"), nargs="?", default="check")
    parser.add_argument("--catalog", type=Path, default=CATALOG)
    parser.add_argument("--runs", type=Path, default=RUNS)
    parser.add_argument("--content", type=Path, default=None, help="directory holding the two milestone pages")
    args = parser.parse_args()
    pages = PAGES if args.content is None else {name: args.content / path.name for name, path in PAGES.items()}
    catalog = load_json(args.catalog)
    if args.command == "build":
        rendered = render(catalog, latest_runs(args.runs))
        for name, text in rendered.items():
            pages[name].parent.mkdir(parents=True, exist_ok=True)
            pages[name].write_text(text, encoding="utf-8")
        print(f"wrote {len(rendered)} pages from {len(latest_runs(args.runs))} built runs")
        return 0
    problems = validate(catalog, pages)
    for problem in problems:
        print(problem)
    print("milestone pages: " + ("pass" if not problems else f"{len(problems)} problems"))
    return 0 if not problems else 1


if __name__ == "__main__":
    sys.exit(main())
