def gap_rows(runs: dict[str, dict[str, Any]]) -> list[str]:
    wanted = (("derived.staking-periods", "gap_without_supply_row", "Staking periods without a supply reading"),
              ("derived.staking-periods", "gap_ended_without_reward_row", "Ended staking periods without a reward transaction"),
              ("snowflake.primary-validator-stakes", "rows_without_reward_status", "Validator stakes in the share without a reward outcome"),
              ("snowflake.primary-delegator-stakes", "rows_without_reward_status", "Delegations in the share without a reward outcome"),
              ("snowflake.primary-validator-stakes", "rows_without_staked_utxo", "Validator stakes in the share without a staked output"),
              ("snowflake.primary-delegator-stakes", "rows_without_staked_utxo", "Delegations in the share without a staked output"),
              ("snowflake.primary-staking-supply", "rows_without_block_supply", "Supply readings in the share without a block supply"),
              ("derived.staking-periods", "open_periods", "Staking periods still open, not a gap"))
    lines = []
    for dataset_id, key, label in wanted:
        value = runs.get(dataset_id, {}).get("build", {}).get("summary", {}).get(key)
        if value:
            lines.append(f"| {label} | `{dataset_id}` | {counted(value)} |")
    return lines or ["| None recorded | | |"]


def pins_text(dataset_id: str, record: dict[str, Any] | None, pinned: dict[str, list[tuple[str, str]]]) -> str:
    items = pinned.get(dataset_id, [])
    if not items:
        return "not pinned"
    current = record["run"] if record else None
    return ", ".join(f"`{pin}` ({run}{', this run' if run == current else ''})" for pin, run in items)


